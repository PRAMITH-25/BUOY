"""
Research Experiment Engine:
Direct side-by-side comparison between:
A. Conventional Continuous Open Sensor Exposure
versus
B. Flow-Through Chamber Measurement

Evaluates:
- Measurement variability (variance)
- Measurement noise (standard deviation, peak-to-peak amplitude)
- Active sampling duration
- Measurements obtained
- Energy consumption per cycle (mWh and Joules)
- Estimated battery life (days)
- Communication overhead

SCIENTIFIC VALIDATION DISCLAIMER:
These results are generated by a digital software prototype to validate software architecture,
state transitions, filtering algorithms, communication protocols, and power budget models.
Simulated results do not prove physical chamber fluid mechanics, real sensor biofouling rates,
or physical pump performance, which require physical hardware testing.
Results depend entirely on the configured simulation parameters.
"""
import math
from typing import Dict, Any, List, Optional
import numpy as np

from buoy_sim.core.seed import global_rng
from buoy_sim.sensors.environment import LakeEnvironment
from buoy_sim.sensors.water_sensors import WaterSensors
from buoy_sim.sensors.ads1115 import ADS1115Emulator
from buoy_sim.sensors.signal_filter import SignalFilter
from buoy_sim.chamber.state_machine import ChamberStateMachine
from buoy_sim.power.power_manager import PowerManager
from buoy_sim.core.events import ChamberState

# Default experiment parameters (configurable via the dashboard)
DEFAULT_EXPERIMENT_PARAMS = {
    "fill_time_s": 30.0,               # Duration of CHAMBER_FILL phase (seconds)
    "stabilize_time_s": 60.0,          # Duration of STABILIZE phase (seconds)
    "flush_time_s": 20.0,              # Duration of FLUSH phase (seconds)
    "measure_duration_s": 8.0,         # Duration of active MEASURE window (seconds)
    "residual_turbidity_factor": 0.85, # Chamber vs open turbidity noise ratio
    "residual_flow_disturbance": 0.90, # Chamber vs open flow noise ratio
    "noise_scale": 1.0,                # Global noise multiplier (1.0 = default)
    "sensor_settling_factor": 0.80,    # Sensor noise during stabilisation vs open
    "pump_energy_j_override": None,    # Optional override for pump energy (Joules)
}


class ComparisonExperiment:
    def __init__(self, duration_s: float = 3600.0, step_s: float = 2.0,
                 params: Optional[Dict[str, Any]] = None):
        self.duration_s = duration_s
        self.step_s = step_s

        # Merge user-provided params with defaults
        self.params = dict(DEFAULT_EXPERIMENT_PARAMS)
        if params:
            for k, v in params.items():
                if k in self.params and v is not None:
                    self.params[k] = v

        # Shared environment
        self.env = LakeEnvironment()

        # System A: Conventional Open Lake Continuous Exposure
        self.sensors_a = WaterSensors()
        self.adc_a = ADS1115Emulator()
        self.filter_a = SignalFilter()
        self.power_a = PowerManager(initial_soc_pct=85.0)

        # System B: Flow-Through Chamber Measurement
        self.sensors_b = WaterSensors()
        self.adc_b = ADS1115Emulator()
        self.filter_b = SignalFilter()
        # Override chamber timing with configurable params
        chamber_timing = {
            "fill_duration_s": self.params["fill_time_s"],
            "stabilize_duration_s": self.params["stabilize_time_s"],
            "flush_duration_s": self.params["flush_time_s"],
            "measure_duration_s": self.params["measure_duration_s"],
        }
        self.chamber_b = ChamberStateMachine(timing_config=chamber_timing)
        self.power_b = PowerManager(initial_soc_pct=85.0)

        # Time-series logs
        self.logs_a: List[Dict[str, Any]] = []
        self.logs_b: List[Dict[str, Any]] = []
        self.comparison_summary: Optional[Dict[str, Any]] = None

    def run(self, progress_callback: Optional[callable] = None) -> Dict[str, Any]:
        """
        Run side-by-side simulation over duration_s.
        """
        self.logs_a.clear()
        self.logs_b.clear()

        sim_time = 3600.0 * 10.0  # 10:00 AM start
        total_steps = int(self.duration_s / self.step_s)

        # Tracking accumulators
        samples_a = {"ph": [], "turbidity": [], "ec": [], "temp": []}
        samples_b = {"ph": [], "turbidity": [], "ec": [], "temp": []}

        energy_a_joules = 0.0
        energy_b_joules = 0.0
        active_sensor_time_a_s = 0.0
        active_sensor_time_b_s = 0.0
        packets_sent_a = 0
        packets_sent_b = 0

        for step_idx in range(total_steps):
            sim_time += self.step_s
            gt = self.env.update(sim_time)
            hour_of_day = gt["hour_of_day"]
            irradiance = gt["solar_irradiance_w_m2"]
            water_temp = gt["water_temp_c"]

            # -------------------------------------------------------------
            # System A: Open Lake Continuous Exposure
            # Sensors exposed directly to lake waves & sunlight 100% of the time
            # -------------------------------------------------------------
            active_sensor_time_a_s += self.step_s
            v_a = self.sensors_a.generate_analog_voltages(
                gt, is_chamber_isolated=False, chamber_stabilized=False
            )
            adc_res_a = self.adc_a.sample_all_channels(v_a)
            proc_a = self.filter_a.process_adc_voltages(adc_res_a["voltages"], v_a["temp_c"])

            # Power A: continuous sensor power, frequent transmissions
            pwr_diag_a = self.power_a.update(
                dt_s=self.step_s,
                solar_irradiance_w_m2=irradiance,
                ambient_temp_c=water_temp,
                hour_of_day=hour_of_day,
                chamber_state="OPEN_WATER",
                pump_active=False,
                is_sampling=True,
                is_lora_tx=(step_idx % 15 == 0),  # every 30s
                is_lora_rx=False,
                is_gps_tracking=True
            )
            energy_a_joules += (pwr_diag_a["load_power_mw"] / 1000.0) * self.step_s
            if step_idx % 15 == 0:
                packets_sent_a += 1

            samples_a["ph"].append(proc_a["filtered"]["ph"])
            samples_a["turbidity"].append(proc_a["filtered"]["turbidity_ntu"])
            samples_a["ec"].append(proc_a["filtered"]["ec_us_cm"])
            samples_a["temp"].append(proc_a["filtered"]["temp_c"])

            log_entry_a = {
                "sim_time_s": sim_time,
                "hour_of_day": hour_of_day,
                "ph": proc_a["filtered"]["ph"],
                "turbidity_ntu": proc_a["filtered"]["turbidity_ntu"],
                "ec_us_cm": proc_a["filtered"]["ec_us_cm"],
                "temp_c": proc_a["filtered"]["temp_c"],
                "soc_pct": pwr_diag_a["battery"]["soc_pct"],
                "power_mw": pwr_diag_a["load_power_mw"],
            }
            self.logs_a.append(log_entry_a)

            # -------------------------------------------------------------
            # System B: Flow-Through Chamber
            # Samples taken during cycle; sensors powered only during measurement window
            # Configurable parameters model simulation assumptions about chamber effects
            # Note: these factors are ASSUMPTIONS and require physical validation
            # -------------------------------------------------------------
            ch_b = self.chamber_b.update(self.step_s)
            is_measuring = self.chamber_b.is_measuring_window
            is_chamber_cycle = self.chamber_b.is_isolated

            if is_measuring:
                active_sensor_time_b_s += self.step_s

            v_b = self.sensors_b.generate_analog_voltages(
                gt,
                is_chamber_isolated=is_chamber_cycle,
                chamber_stabilized=self.chamber_b.fluid_stabilized
            )
            adc_res_b = self.adc_b.sample_all_channels(v_b)
            proc_b = self.filter_b.process_adc_voltages(adc_res_b["voltages"], v_b["temp_c"])

            # Power B: pump on during fill/flush, sensors on during measure, sleep otherwise
            pwr_diag_b = self.power_b.update(
                dt_s=self.step_s,
                solar_irradiance_w_m2=irradiance,
                ambient_temp_c=water_temp,
                hour_of_day=hour_of_day,
                chamber_state=ch_b["current_state"],
                pump_active=ch_b["pump_active"],
                is_sampling=is_measuring,
                is_lora_tx=(ch_b["transitioned"] and ch_b["current_state"] == ChamberState.MEASURE.value),
                is_lora_rx=False,
                is_gps_tracking=is_chamber_cycle
            )
            energy_b_joules += (pwr_diag_b["load_power_mw"] / 1000.0) * self.step_s

            if ch_b["transitioned"] and ch_b["current_state"] == ChamberState.MEASURE.value:
                packets_sent_b += 1

            # Only record valid measurements during the stabilized chamber window
            if is_measuring:
                samples_b["ph"].append(proc_b["filtered"]["ph"])
                samples_b["turbidity"].append(proc_b["filtered"]["turbidity_ntu"])
                samples_b["ec"].append(proc_b["filtered"]["ec_us_cm"])
                samples_b["temp"].append(proc_b["filtered"]["temp_c"])

            log_entry_b = {
                "sim_time_s": sim_time,
                "hour_of_day": hour_of_day,
                "chamber_state": ch_b["current_state"],
                "ph": proc_b["filtered"]["ph"],
                "turbidity_ntu": proc_b["filtered"]["turbidity_ntu"],
                "ec_us_cm": proc_b["filtered"]["ec_us_cm"],
                "temp_c": proc_b["filtered"]["temp_c"],
                "soc_pct": pwr_diag_b["battery"]["soc_pct"],
                "power_mw": pwr_diag_b["load_power_mw"],
            }
            self.logs_b.append(log_entry_b)

            if progress_callback and step_idx % 25 == 0:
                progress_callback(step_idx / total_steps)

        # -------------------------------------------------------------
        # Compute Statistical Metrics for Comparison
        # -------------------------------------------------------------
        def compute_stats(arr):
            a = np.array(arr) if len(arr) > 0 else np.array([0.0])
            mean_val = float(np.mean(a))
            std_val = float(np.std(a))
            var_val = float(np.var(a))
            ptp_val = float(np.ptp(a))
            snr_db = 20.0 * math.log10(abs(mean_val) / max(1e-6, std_val)) if std_val > 1e-6 else 99.0
            return {
                "mean": round(mean_val, 4),
                "std": round(std_val, 5),
                "variance": round(var_val, 6),
                "ptp": round(ptp_val, 4),
                "snr_db": round(snr_db, 2),
            }

        stats_a = {p: compute_stats(samples_a[p]) for p in samples_a}
        stats_b = {p: compute_stats(samples_b[p]) for p in samples_b}

        # Energy & Battery metrics
        # Li-ion 16.28 Wh = 58,608 Joules
        battery_total_joules = 16.28 * 3600.0
        cycles_completed_b = max(1, self.chamber_b.total_cycles_completed)
        energy_per_cycle_b_j = energy_b_joules / cycles_completed_b
        energy_per_cycle_b_mwh = (energy_per_cycle_b_j / 3600.0) * 1000.0

        # Equivalent cycle energy for continuous mode (per 5 min window)
        cycles_equiv_a = max(1, int(self.duration_s / 300.0))
        energy_per_cycle_a_j = energy_a_joules / cycles_equiv_a
        energy_per_cycle_a_mwh = (energy_per_cycle_a_j / 3600.0) * 1000.0

        # Estimated endurance (days) without solar
        avg_power_a_w = (energy_a_joules / self.duration_s)
        avg_power_b_w = (energy_b_joules / self.duration_s)
        endurance_days_a = (16.28 / max(0.01, avg_power_a_w)) / 24.0
        endurance_days_b = (16.28 / max(0.01, avg_power_b_w)) / 24.0

        # Noise reduction percentages
        noise_reduction = {}
        for p in ["ph", "turbidity", "ec", "temp"]:
            std_a = stats_a[p]["std"]
            std_b = stats_b[p]["std"]
            reduct = max(0.0, (1.0 - (std_b / max(1e-6, std_a))) * 100.0) if std_a > 1e-6 else 0.0
            noise_reduction[p] = round(reduct, 1)

        # Active sampling duty cycle percentage
        duty_cycle_b_pct = round(100.0 * active_sensor_time_b_s / max(1.0, self.duration_s), 2)
        duty_cycle_a_pct = 100.0

        self.comparison_summary = {
            "disclaimer": (
                "SIMULATED COMPARISON — Results produced by a digital software prototype. "
                "Noise reduction figures depend on the simulation parameters configured. "
                "These results DO NOT prove physical chamber fluid dynamics, real sensor biofouling "
                "reduction, pump mechanics, or any hardware property. "
                "Physical validation on real hardware is required before claiming performance advantages."
            ),
            "validation_note": (
                "Results depend on simulation parameters and require physical validation. "
                "The chamber is NOT guaranteed to always produce better results."
            ),
            "simulation_params_used": dict(self.params),
            "duration_hours": round(self.duration_s / 3600.0, 2),
            "open_water_system_a": {
                "label": "Conventional Continuous Open Lake Exposure",
                "statistics": stats_a,
                "measurements_count": len(samples_a["ph"]),
                "active_sampling_duration_s": round(active_sensor_time_a_s, 1),
                "duty_cycle_pct": duty_cycle_a_pct,
                "energy_consumed_joules": round(energy_a_joules, 1),
                "energy_consumed_wh": round(energy_a_joules / 3600.0, 3),
                "energy_per_cycle_mwh": round(energy_per_cycle_a_mwh, 2),
                "avg_power_mw": round(avg_power_a_w * 1000.0, 1),
                "estimated_battery_endurance_days": round(endurance_days_a, 1),
                "packets_transmitted": packets_sent_a,
            },
            "chamber_system_b": {
                "label": "Flow-Through Chamber Measurement",
                "statistics": stats_b,
                "measurements_count": len(samples_b["ph"]),
                "active_sampling_duration_s": round(active_sensor_time_b_s, 1),
                "duty_cycle_pct": duty_cycle_b_pct,
                "energy_consumed_joules": round(energy_b_joules, 1),
                "energy_consumed_wh": round(energy_b_joules / 3600.0, 3),
                "energy_per_cycle_mwh": round(energy_per_cycle_b_mwh, 2),
                "avg_power_mw": round(avg_power_b_w * 1000.0, 1),
                "estimated_battery_endurance_days": round(endurance_days_b, 1),
                "cycles_completed": self.chamber_b.total_cycles_completed,
                "packets_transmitted": packets_sent_b,
            },
            "comparison_delta": {
                "noise_reduction_pct": noise_reduction,
                "energy_savings_pct": round(max(0.0, (1.0 - (energy_b_joules / max(1.0, energy_a_joules))) * 100.0), 1),
                "battery_life_multiplier": round(endurance_days_b / max(0.1, endurance_days_a), 2),
                "comm_overhead_reduction_pct": round(max(0.0, (1.0 - (packets_sent_b / max(1, packets_sent_a))) * 100.0), 1),
                "active_sampling_duty_cycle_reduction_pct": round(max(0.0, duty_cycle_a_pct - duty_cycle_b_pct), 2),
            }
        }
        return self.comparison_summary
